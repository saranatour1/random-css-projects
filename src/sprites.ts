// Rows of palette chars become a crisp SVG data URI, one <rect> per horizontal run of a color.
export function sprite(rows: string[], swap: Record<string, string> = {}) {
  const w = rows[0].length
  let rects = ''
  rows.forEach((row, y) => {
    if (row.length !== w) throw new Error(`sprite row ${y} "${row}" is ${row.length} wide, expected ${w}`)
    for (let x = 0, e = 0; x < w; x = e) {
      const c = row[x]
      for (e = x + 1; row[e] === c; e++);
      if (c === '.') continue
      const fill = swap[c] ?? PAL[c]
      if (!fill) throw new Error(`sprite char "${c}" has no color`)
      rects += `<rect x="${x}" y="${y}" width="${e - x}" height="1" fill="${fill}"/>`
    }
  })
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${rows.length}" shape-rendering="crispEdges">${rects}</svg>`
  return `url("data:image/svg+xml,${svg.replace(/"/g, "'").replace(/#/g, '%23')}")`
}

